package org.example

fun main() {

    // var is mutable  - can be change
    var name = "Neha"
    println(name)

    name = "Pooja"
    println(name)

    // val is immutable - cannot be change
    val name1 = "Neha"
    println(name1)

    // if we print here like
    // name1 = "Pooja" then show the error
}