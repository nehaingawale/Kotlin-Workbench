package org.example

fun main() {

    // For loop
    for (i in 1..10){
        println(i)
    }

    println("---------")

    // While loop
    var i=1
    while(i<=5){
        println(i)
        i++
    }

    println("---------")

    // do-while loop
    do{
        println(i)
        i++
    }while(i<=5)
}